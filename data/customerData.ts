// Helper to construct seeded revisions
const createSeedRevision = (
  id: string,
  customerId: string,
  customerName: string,
  boxId: string,
  boxName: string,
  revisionNo: number,
  formattedDate: string,
  timestamp: number,
  reason: string,
  dimensions: any,
  paper: any,
  printing: any,
  finishing: any,
  converting: any,
  production: any,
  priceDiffFromPrevious?: number,
  percentDiffFromPrevious?: number
): PriceRevision => {
  const result = calculatePackagingCosts(
    'tuck_end',
    dimensions,
    paper,
    printing,
    finishing,
    converting,
    production
  );
  const quantityTiers = calculateQuantityTiers(
    'tuck_end',
    dimensions,
    paper,
    printing,
    finishing,
    converting,
    production
  );

  return {
    id,
    customerId,
    customerName,
    boxId,
    boxName,
    boxCategory: 'tuck_end',
    timestamp,
    formattedDate,
    revisionNo,
    reason,
    dimensions,
    paper,
    printing,
    finishing,
    converting,
    production,
    result,
    quantityTiers,
    unitCost: result.totalCostPerUnit,
    sellingPrice: result.sellingPricePerUnit,
    totalProfit: result.totalProfit,
    priceDiffFromPrevious,
    percentDiffFromPrevious,
  };
};

